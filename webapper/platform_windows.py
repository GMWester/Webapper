"""Windows backend: Mozilla's full Firefox installer extracted with
/ExtractDir (no system install, no admin rights), a per-app launcher .exe
compiled with the C# compiler that ships with Windows (.NET Framework 4),
Start-menu/desktop shortcuts and an "Apps & features" uninstall entry."""

from __future__ import annotations

import base64
import os
import platform
import shutil
import subprocess
import tempfile

from .core import AppRecord, AppSpec, Log, WebApperError, bouncer_url, cached_download

UNINSTALL_KEY = r"Software\Microsoft\Windows\CurrentVersion\Uninstall"
NO_WINDOW = 0x08000000  # CREATE_NO_WINDOW


def _env(var: str, fallback: str) -> str:
    return os.environ.get(var) or os.path.expanduser(fallback)


def native_arch() -> str:
    """'arm64' or 'x64' for the real CPU, even when running emulated."""
    try:
        import ctypes

        process_machine = ctypes.c_ushort()
        native_machine = ctypes.c_ushort()
        k32 = ctypes.windll.kernel32
        if k32.IsWow64Process2(k32.GetCurrentProcess(), ctypes.byref(process_machine), ctypes.byref(native_machine)):
            return "arm64" if native_machine.value == 0xAA64 else "x64"
    except Exception:
        pass
    return "arm64" if platform.machine().upper() in ("ARM64", "AARCH64") else "x64"


def _ps_quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def run_powershell(script: str) -> str:
    enc = base64.b64encode(script.encode("utf-16-le")).decode()
    out = subprocess.run(
        ["powershell.exe", "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-EncodedCommand", enc],
        capture_output=True, text=True, creationflags=NO_WINDOW,
    )
    if out.returncode != 0:
        raise WebApperError(f"PowerShell failed: {out.stderr.strip() or out.stdout.strip()}")
    return out.stdout.strip()


def find_csc() -> str | None:
    windir = os.environ.get("WINDIR", r"C:\Windows")
    for fw in ("Framework64", "Framework"):
        p = os.path.join(windir, "Microsoft.NET", fw, "v4.0.30319", "csc.exe")
        if os.path.exists(p):
            return p
    return None


def _cs_verbatim(s: str) -> str:
    return '@"' + s.replace('"', '""') + '"'


LAUNCHER_CS = r"""
using System;
using System.Diagnostics;
using System.IO;
using System.Reflection;
[assembly: AssemblyTitle(TITLE)]
[assembly: AssemblyProduct(TITLE)]
[assembly: AssemblyDescription("Web app generated by WebApper")]
static class WebAppLauncher {
    [STAThread]
    static int Main(string[] args) {
        string here = AppDomain.CurrentDomain.BaseDirectory;
        string firefox = Path.GetFullPath(Path.Combine(here, FIREFOX));
        string profile = Path.GetFullPath(Path.Combine(here, PROFILE));
        if (!File.Exists(firefox)) {
            System.Windows.Forms.MessageBox.Show("Firefox runtime not found:\n" + firefox, TITLE);
            return 1;
        }
        var psi = new ProcessStartInfo(firefox);
        string extra = string.Join(" ", Array.ConvertAll(args, a => "\"" + a.Replace("\"", "\\\"") + "\""));
        psi.Arguments = "-profile \"" + profile + "\" " + FLAGS + " " + extra;
        psi.UseShellExecute = false;
        psi.WorkingDirectory = here;
        Process.Start(psi);
        return 0;
    }
}
"""


class WindowsPlatform:
    key = "windows"
    display_name = "Windows"
    supported_modes = ("local", "portable")
    supports_desktop_shortcut = True
    supports_steam = False

    def data_root(self) -> str:
        return os.path.join(_env("LOCALAPPDATA", "~/AppData/Local"), "WebApper")

    def cache_root(self) -> str:
        return os.path.join(self.data_root(), "cache")

    def default_portable_parent(self) -> str:
        return os.path.join(_env("USERPROFILE", "~"), "WebApps")

    def portable_entry(self, name: str) -> str:
        return name

    def portable_layout(self, parent: str, name: str) -> tuple[str, str, str]:
        app_dir = os.path.join(parent, name)
        return app_dir, os.path.join(app_dir, "runtime"), os.path.join(app_dir, "profile")

    def start_menu_dir(self) -> str:
        return os.path.join(_env("APPDATA", "~/AppData/Roaming"), "Microsoft", "Windows", "Start Menu", "Programs", "WebApper")

    def desktop_dir(self) -> str:
        try:
            return run_powershell("[Environment]::GetFolderPath('Desktop')")
        except Exception:
            return os.path.join(_env("USERPROFILE", "~"), "Desktop")

    # ------------------------------------------------------------ runtime
    def firefox_binary(self, runtime_dir: str) -> str:
        return os.path.join(runtime_dir, "firefox.exe")

    def ensure_runtime(self, runtime_dir: str, channel: str, log: Log, fresh_copy: bool = False) -> str:
        exe = self.firefox_binary(runtime_dir)
        if os.path.exists(exe) and not fresh_copy:
            log("Firefox runtime already installed.")
            return exe
        os_name = "win64-aarch64" if native_arch() == "arm64" else "win64"
        setup = cached_download(
            bouncer_url(channel, os_name), self.cache_root(), f"firefox-{channel}-{os_name}-setup.exe", log
        )
        log("Extracting Firefox (no system install needed)…")
        tmp = tempfile.mkdtemp(prefix="webapper-ff-")
        try:
            # /ExtractDir must be the first (and only) switch.
            res = subprocess.run([setup, f"/ExtractDir={tmp}"], capture_output=True, creationflags=NO_WINDOW)
            src = os.path.join(tmp, "core") if os.path.isdir(os.path.join(tmp, "core")) else tmp
            if res.returncode != 0 or not os.path.exists(os.path.join(src, "firefox.exe")):
                os.remove(setup)
                raise WebApperError(f"Could not extract Firefox (exit code {res.returncode}). Please retry.")
            if os.path.isdir(runtime_dir):
                shutil.rmtree(runtime_dir, ignore_errors=True)
            shutil.copytree(src, runtime_dir)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        return exe

    # ------------------------------------------------------------ app
    def extra_prefs(self, spec: AppSpec) -> dict:
        # Separate taskbar button per app instead of grouping under Firefox.
        return {"taskbar.grouping.useprofile": True}

    def flags(self, record: AppRecord) -> str:
        return "-kiosk" if record.kiosk else ""

    def build_launcher(self, record: AppRecord, ico: str, exe_path: str, firefox_rel: str, profile_rel: str) -> str:
        """Compile <Name>.exe; falls back to a .cmd if no C# compiler exists."""
        csc = find_csc()
        if csc:
            src = (
                LAUNCHER_CS.replace("TITLE", _cs_verbatim(record.name))
                .replace("FIREFOX", _cs_verbatim(firefox_rel))
                .replace("PROFILE", _cs_verbatim(profile_rel))
                .replace("FLAGS", _cs_verbatim(self.flags(record)))
            )
            with tempfile.TemporaryDirectory() as d:
                cs = os.path.join(d, "launcher.cs")
                with open(cs, "w", encoding="utf-8") as f:
                    f.write(src)
                res = subprocess.run(
                    [csc, "/nologo", "/target:winexe", "/optimize+", "/r:System.Windows.Forms.dll",
                     f"/win32icon:{ico}", f"/out:{exe_path}", cs],
                    capture_output=True, text=True, creationflags=NO_WINDOW,
                )
            if res.returncode == 0 and os.path.exists(exe_path):
                return exe_path
        cmd_path = os.path.splitext(exe_path)[0] + ".cmd"
        ff = firefox_rel if os.path.isabs(firefox_rel) else "%~dp0" + firefox_rel
        prof = profile_rel if os.path.isabs(profile_rel) else "%~dp0" + profile_rel
        with open(cmd_path, "w", encoding="utf-8") as f:
            f.write(
                "@echo off\r\n"
                f'start "" "{ff}" -profile "{prof}" {self.flags(record)} %*\r\n'
            )
        return cmd_path

    def create_shortcut(self, lnk: str, target: str, args: str, icon: str, workdir: str, desc: str) -> None:
        os.makedirs(os.path.dirname(lnk), exist_ok=True)
        run_powershell(
            "$s=(New-Object -ComObject WScript.Shell).CreateShortcut(" + _ps_quote(lnk) + ");"
            f"$s.TargetPath={_ps_quote(target)};$s.Arguments={_ps_quote(args)};"
            f"$s.IconLocation={_ps_quote(icon + ',0')};$s.WorkingDirectory={_ps_quote(workdir)};"
            f"$s.Description={_ps_quote(desc)};$s.Save()"
        )

    def finalize(self, record: AppRecord, spec: AppSpec, icon, log: Log) -> None:
        ico = os.path.join(record.app_dir, "icon.ico")
        icon.save(ico, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
        icon.save(os.path.join(record.app_dir, "icon.png"))
        exe_name = f"{record.name}.exe"
        if record.mode == "portable":
            record.launcher = self.build_launcher(
                record, ico, os.path.join(record.app_dir, exe_name), r"runtime\firefox.exe", "profile"
            )
            with open(os.path.join(record.app_dir, "README.txt"), "w", encoding="utf-8") as f:
                f.write(
                    f"{record.name} (portable web app made with WebApper)\r\n\r\n"
                    f"Start it with {os.path.basename(record.launcher)}.\r\n"
                    "Firefox, add-ons, logins and settings all live in this folder, so it can\r\n"
                    "be moved to a USB drive or another Windows PC.\r\n"
                )
            return

        firefox = self.firefox_binary(record.runtime_dir)
        record.launcher = self.build_launcher(
            record, ico, os.path.join(record.app_dir, exe_name), firefox, record.profile_dir
        )
        args = f'-profile "{record.profile_dir}" {self.flags(record)}'.strip()
        lnk = os.path.join(self.start_menu_dir(), f"{record.name}.lnk")
        self.create_shortcut(lnk, firefox, args, ico, record.app_dir, record.url)
        record.shortcuts.append(lnk)
        if spec.desktop_shortcut:
            dl = os.path.join(self.desktop_dir(), f"{record.name}.lnk")
            self.create_shortcut(dl, firefox, args, ico, record.app_dir, record.url)
            record.shortcuts.append(dl)
        self.register_uninstall(record, ico)

    def register_uninstall(self, record: AppRecord, ico: str) -> None:
        key_name = f"WebApper-{record.id}"
        lines = ["@echo off", f'title Uninstall {record.name}']
        for s in record.shortcuts:
            lines.append(f'del /f /q "{s}" 2>nul')
        lines += [
            f'reg delete "HKCU\\{UNINSTALL_KEY}\\{key_name}" /f >nul 2>&1',
            'cd /d "%TEMP%"',
            # "(goto)" lets the batch file delete the folder it lives in.
            f'(goto) 2>nul & rmdir /s /q "{record.app_dir}"',
        ]
        script = os.path.join(record.app_dir, "uninstall.cmd")
        with open(script, "w", encoding="utf-8") as f:
            f.write("\r\n".join(lines) + "\r\n")
        try:
            import winreg

            with winreg.CreateKey(winreg.HKEY_CURRENT_USER, f"{UNINSTALL_KEY}\\{key_name}") as k:
                winreg.SetValueEx(k, "DisplayName", 0, winreg.REG_SZ, record.name)
                winreg.SetValueEx(k, "DisplayIcon", 0, winreg.REG_SZ, ico)
                winreg.SetValueEx(k, "Publisher", 0, winreg.REG_SZ, "WebApper")
                winreg.SetValueEx(k, "URLInfoAbout", 0, winreg.REG_SZ, record.url)
                winreg.SetValueEx(k, "InstallLocation", 0, winreg.REG_SZ, record.app_dir)
                winreg.SetValueEx(k, "UninstallString", 0, winreg.REG_SZ, f'cmd.exe /c "{script}"')
                winreg.SetValueEx(k, "NoModify", 0, winreg.REG_DWORD, 1)
                winreg.SetValueEx(k, "NoRepair", 0, winreg.REG_DWORD, 1)
            record.extra["uninstall_key"] = key_name
        except ImportError:
            pass

    def remove(self, record: AppRecord, log: Log) -> None:
        for s in record.shortcuts:
            try:
                os.remove(s)
            except FileNotFoundError:
                pass
        key_name = record.extra.get("uninstall_key")
        if key_name:
            try:
                import winreg

                winreg.DeleteKey(winreg.HKEY_CURRENT_USER, f"{UNINSTALL_KEY}\\{key_name}")
            except (ImportError, OSError):
                pass

    def launch(self, record: AppRecord) -> None:
        if record.launcher.endswith(".cmd"):
            subprocess.Popen(["cmd.exe", "/c", record.launcher], creationflags=NO_WINDOW)
        else:
            subprocess.Popen([record.launcher], creationflags=NO_WINDOW)


PLATFORM = WindowsPlatform()
